/// Crops [level]'s (`x`,`y`)-`width`x`height` rectangle — see [readSvsRegion]
/// for coordinate semantics — and re-encodes it as a brand new, valid
/// multi-level pyramidal `.svs` file (a tiled BigTIFF with JPEG-compressed
/// tiles and an Aperio-style `ImageDescription`), rather than a single flat
/// raster image. The result can be reopened with [SvsFile.open] — by this
/// package or any other tiled-TIFF/OpenSlide-aware tool — and panned/zoomed
/// like any other slide.
///
/// [tileSize] is the tile edge length for every generated level (default
/// 256, matching real Aperio files). [quality] (1-100) is the JPEG quality
/// for every tile. Levels are generated by halving the previous level's
/// dimensions (box-filter downsampled) until one fits in a single tile —
/// the same shape a real Aperio pyramid takes. [adjustments] (default
/// [SvsImageAdjustments.none]) is applied once, to the source crop, before
/// the pyramid is built — every generated level reflects it.
///
/// The exported file always gets a thumbnail (needed for `SvsImageView`'s
/// minimap) generated from the crop itself, but two other pieces of the
/// source file are opt-in/opt-out, since a crop is often shared outside the
/// context that made them meaningful: [includeLabelAndMacroImages] (default
/// `true`) copies the source file's own label/macro associated images
/// across unmodified — they describe the whole physical slide, not just the
/// cropped region, so a caller cropping out a small region to share might
/// not want the slide's label riding along; pass `false` to omit them (and
/// shrink the output). [includeSourceMetadata] (default `true`) carries
/// every other `ImageDescription` field the source file had (Filename,
/// Date, Time, User, ScanScope ID, etc. — anything beyond the `AppMag`/`MPP`
/// this function always recomputes for the crop) into the exported file's
/// own `ImageDescription`; pass `false` for just `AppMag`/`MPP`, e.g. to
/// avoid carrying the original filename/scanner details into a
/// redistributed crop.
///
/// Built by streaming the source region band-by-band (bounded memory —
/// roughly `tileSize * width * 4` bytes regardless of how tall the crop is,
/// not `width * height * 4`), so there's no pixel-count safety limit by
/// default. [maxPixels], if given, still throws [ArgumentError] up front for
/// a crop over that size — useful if a caller wants to keep the old
/// fail-fast behavior for a specific size budget. [onProgress] (0.0-1.0), if
/// given, is invoked as each band of the source is processed.
///
/// This returns the whole encoded file as bytes, which — unlike building the
/// file itself — *does* need that many bytes of RAM to hold the return
/// value. For a crop large enough that this matters, prefer
/// [exportSvsRegionAsSvsToFile], which streams straight to disk instead.
///
/// Must run on the main isolate, like [readSvsRegion].
Future<Uint8List> exportSvsRegionAsSvs(
  SvsFile svsFile, {
  required int level,
  required int x,
  required int y,
  required int width,
  required int height,
  int tileSize = 256,
  int quality = 90,
  int? maxPixels,
  SvsImageAdjustments adjustments = SvsImageAdjustments.none,
  bool includeLabelAndMacroImages = true,
  bool includeSourceMetadata = true,
  void Function(double progress)? onProgress,
}) async {
  final tempDir = await Directory.systemTemp.createTemp('svs_region_export_');
  final tempFile = File('${tempDir.path}/region.svs');
  try {
    await _streamSvsRegionAsSvs(
      svsFile,
      outFile: tempFile,
      level: level,
      x: x,
      y: y,
      width: width,
      height: height,
      tileSize: tileSize,
      quality: quality,
      maxPixels: maxPixels,
      adjustments: adjustments,
      includeLabelAndMacroImages: includeLabelAndMacroImages,
      includeSourceMetadata: includeSourceMetadata,
      onProgress: onProgress,
    );
    return await tempFile.readAsBytes();
  } finally {
    await tempDir.delete(recursive: true);
  }
}

/// Same as [exportSvsRegionAsSvs], but streams the encoded file straight to
/// [path] instead of returning it — the memory-bounded way to export a
/// crop that's too large to comfortably hold as a single in-memory
/// [Uint8List].
Future<File> exportSvsRegionAsSvsToFile(
  SvsFile svsFile, {
  required String path,
  required int level,
  required int x,
  required int y,
  required int width,
  required int height,
  int tileSize = 256,
  int quality = 90,
  int? maxPixels,
  SvsImageAdjustments adjustments = SvsImageAdjustments.none,
  bool includeLabelAndMacroImages = true,
  bool includeSourceMetadata = true,
  void Function(double progress)? onProgress,
}) async {
  final file = File(path);
  await _streamSvsRegionAsSvs(
    svsFile,
    outFile: file,
    level: level,
    x: x,
    y: y,
    width: width,
    height: height,
    tileSize: tileSize,
    quality: quality,
    maxPixels: maxPixels,
    adjustments: adjustments,
    includeLabelAndMacroImages: includeLabelAndMacroImages,
    includeSourceMetadata: includeSourceMetadata,
    onProgress: onProgress,
  );
  return file;
}

Future<void> _streamSvsRegionAsSvs(
  SvsFile svsFile, {
  required File outFile,
  required int level,
  required int x,
  required int y,
  required int width,
  required int height,
  required int tileSize,
  required int quality,
  required int? maxPixels,
  required SvsImageAdjustments adjustments,
  required bool includeLabelAndMacroImages,
  required bool includeSourceMetadata,
  required void Function(double progress)? onProgress,
}) async {
  if (level < 0 || level >= svsFile.levels.length) {
    throw SvsFormatException(
      'Level $level out of range (have ${svsFile.levels.length} levels)',
    );
  }
  if (tileSize <= 0) {
    throw ArgumentError.value(tileSize, 'tileSize', 'must be positive');
  }
  if (width <= 0 || height <= 0) {
    throw ArgumentError('width/height must be positive, got ${width}x$height');
  }
  final pixelCount = width * height;
  if (maxPixels != null && pixelCount > maxPixels) {
    final estimatedMb = (pixelCount * 4 / (1024 * 1024)).round();
    throw ArgumentError(
      'Requested region is ${width}x$height ($pixelCount px), over the '
      '$maxPixels px safety limit (~$estimatedMb MB just for the raw pixel '
      'buffer). Crop a smaller rectangle, or pass a higher maxPixels if you '
      'really mean it.',
    );
  }

  final sourceLevel = svsFile.levels[level];
  final sourceMppX = svsFile.metadata.mppX;
  final mpp = sourceMppX == null ? null : sourceMppX * sourceLevel.downsample;
  final appMag = svsFile.metadata.appMag;

  // The source file's own label/macro associated images don't change with
  // the crop — they describe the whole physical slide — so, unless the
  // caller opted out via `includeLabelAndMacroImages`, they're carried into
  // the exported file unmodified (raw strip bytes copied as-is, no decode/
  // re-encode) rather than dropped, same as a real Aperio file would have
  // them.
  final labelAndMacroImages = includeLabelAndMacroImages
      ? svsFile.associatedImages
            .where(
              (a) =>
                  a.kind == AssociatedImageKind.label ||
                  a.kind == AssociatedImageKind.macro,
            )
            .toList(growable: false)
      : const <SvsAssociatedImage>[];

  final levelDims = computePyramidLevelDims(width, height, tileSize);
  final specs = [
    for (var i = 0; i < levelDims.length; i++)
      PyramidLevelSpec(
        width: levelDims[i].$1,
        height: levelDims[i].$2,
        tileWidth: tileSize,
        tileLength: tileSize,
        imageDescription: i == 0
            ? _buildImageDescription(
                width: levelDims[0].$1,
                height: levelDims[0].$2,
                tileSize: tileSize,
                quality: quality,
                mpp: mpp,
                appMag: appMag,
                sourceFields: includeSourceMetadata
                    ? svsFile.metadata.raw
                    : const {},
              )
            : null,
      ),
  ];
  // The coarsest generated level (last in `specs`, already <= tileSize in
  // both dimensions) doubles as the exported file's thumbnail — an
  // associated image `SvsImageView`'s minimap needs, same as a real Aperio
  // file carries, which a plain pyramid-levels-only export previously never
  // wrote at all.
  final thumbSpec = AssociatedImageSpec(
    width: levelDims.last.$1,
    height: levelDims.last.$2,
    compression: ApCompression.newJpeg,
    photometricInterpretation: 6, // YCbCr — img.encodeJpg's normal output
    samplesPerPixel: 3,
    bitsPerSample: const [8, 8, 8],
    predictor: 1,
    rowsPerStrip: levelDims.last.$2,
    stripCount: 1,
  );
  final extraSpecs = [
    for (final image in labelAndMacroImages) await _copySpec(image),
  ];
  final layout = planPyramidHeader(
    specs,
    associatedImages: [thumbSpec, ...extraSpecs],
  );

  if (await outFile.exists()) await outFile.delete();
  final raf = await outFile.open(mode: FileMode.write);
  try {
    await raf.writeFrom(layout.headerBytes);

    final sink = _TileSink(raf, specs.length);
    final builders = [
      for (var i = 0; i < specs.length; i++)
        _LevelBuilder(
          levelIndex: i,
          spec: specs[i],
          quality: quality,
          sink: sink,
        ),
    ];
    for (var i = 0; i < builders.length - 1; i++) {
      builders[i].next = builders[i + 1];
    }

    var rowsProcessed = 0;
    var srcY = 0;
    while (srcY < height) {
      final bandHeight = math.min(tileSize, height - srcY);
      final raw = await readSvsRegionRawRgba(
        svsFile,
        level: level,
        x: x,
        y: y + srcY,
        width: width,
        height: bandHeight,
      );
      adjustments.applyToRgba(raw);
      await builders[0].addRows([
        for (var r = 0; r < bandHeight; r++)
          Uint8List.sublistView(raw, r * width * 4, (r + 1) * width * 4),
      ]);

      rowsProcessed += bandHeight;
      srcY += bandHeight;
      onProgress?.call(rowsProcessed / height);
      // Yield between bands so the UI (this all runs on the main isolate —
      // tile decoding needs `dart:ui`) can still service a frame.
      await Future(() {});
    }
    await builders[0].finish();
    // Captured after every level (including the coarsest, which never has a
    // `next`) has finished — `_LevelBuilder._emitBand` only ever runs once
    // for the coarsest level, covering its whole (already <= tileSize)
    // extent in one band, so this is the complete thumbnail image.
    final thumbnailImage = builders.last.finalImage!;
    var writePos = await raf.position();

    final thumbBytes = img.encodeJpg(thumbnailImage, quality: quality);
    final thumbOffset = writePos;
    await raf.setPosition(writePos);
    await raf.writeFrom(thumbBytes);
    writePos += thumbBytes.length;
    if (writePos.isOdd) {
      await raf.writeFrom(Uint8List(1));
      writePos += 1;
    }

    // Each label/macro image's strips are copied byte-for-byte (no decode,
    // no re-encode) straight from the source file.
    final extraStripData = <(List<int>, List<int>)>[];
    for (final source in labelAndMacroImages) {
      final stripCount = await source.stripCount;
      final offsets = <int>[];
      final byteCounts = <int>[];
      for (var i = 0; i < stripCount; i++) {
        final bytes = await source.readRawStripBytes(i);
        if (bytes.isEmpty) {
          offsets.add(0);
          byteCounts.add(0);
          continue;
        }
        offsets.add(writePos);
        byteCounts.add(bytes.length);
        await raf.setPosition(writePos);
        await raf.writeFrom(bytes);
        writePos += bytes.length;
        if (writePos.isOdd) {
          await raf.writeFrom(Uint8List(1));
          writePos += 1;
        }
      }
      extraStripData.add((offsets, byteCounts));
    }

    for (var i = 0; i < specs.length; i++) {
      final patch = layout.levels[i];
      await raf.setPosition(patch.tileOffsetsValuePos);
      await raf.writeFrom(
        encodeTiffInts(sink.offsetsPerLevel[i], TiffType.long8),
      );
      await raf.setPosition(patch.tileByteCountsValuePos);
      await raf.writeFrom(
        encodeTiffInts(sink.byteCountsPerLevel[i], TiffType.long),
      );
    }

    final thumbPatch = layout.associatedImages[0];
    await raf.setPosition(thumbPatch.stripOffsetsValuePos);
    await raf.writeFrom(encodeTiffInts([thumbOffset], TiffType.long8));
    await raf.setPosition(thumbPatch.stripByteCountsValuePos);
    await raf.writeFrom(encodeTiffInts([thumbBytes.length], TiffType.long));

    for (var i = 0; i < labelAndMacroImages.length; i++) {
      final patch = layout.associatedImages[1 + i];
      final (offsets, byteCounts) = extraStripData[i];
      await raf.setPosition(patch.stripOffsetsValuePos);
      await raf.writeFrom(encodeTiffInts(offsets, TiffType.long8));
      await raf.setPosition(patch.stripByteCountsValuePos);
      await raf.writeFrom(encodeTiffInts(byteCounts, TiffType.long));
    }
  } finally {
    await raf.close();
  }
}

/// Builds an [AssociatedImageSpec] that lets [image]'s strips be copied
/// byte-for-byte into the exported file — same compression/photometric/
/// sample layout/JPEGTables/description as the source, so the copy decodes
/// identically once reopened.
Future<AssociatedImageSpec> _copySpec(SvsAssociatedImage image) async {
  return AssociatedImageSpec(
    width: image.width,
    height: image.height,
    compression: image.compression,
    photometricInterpretation: image.photometricInterpretation,
    samplesPerPixel: image.samplesPerPixel,
    bitsPerSample: image.bitsPerSample,
    predictor: image.predictor,
    rowsPerStrip: await image.rowsPerStrip,
    stripCount: await image.stripCount,
    jpegTables: image.isJpeg ? await image.jpegTables : null,
    imageDescription: await image.imageDescription,
  );
}

/// Sequentially appends tile JPEG bytes to the output file (starting right
/// after the header `planPyramidHeader` already wrote), recording each
/// tile's final file offset/byte-count for the header patch pass. Tiles for
/// a level must be written in row-major (`ty * tilesAcrossX + tx`) order —
/// `_LevelBuilder` always emits full tile-row bands in that order, so this
/// never needs to reorder anything.
class _TileSink {
  final RandomAccessFile raf;
  final List<List<int>> offsetsPerLevel;
  final List<List<int>> byteCountsPerLevel;
  int _pos = -1;

  _TileSink(this.raf, int levelCount)
    : offsetsPerLevel = List.generate(levelCount, (_) => <int>[]),
      byteCountsPerLevel = List.generate(levelCount, (_) => <int>[]);

  Future<void> writeTile(int levelIndex, Uint8List bytes) async {
    _pos = _pos < 0 ? await raf.position() : _pos;
    offsetsPerLevel[levelIndex].add(_pos);
    byteCountsPerLevel[levelIndex].add(bytes.length);
    await raf.writeFrom(bytes);
    _pos += bytes.length;
    if (_pos.isOdd) {
      await raf.writeFrom(Uint8List(1));
      _pos += 1;
    }
  }
}

/// Builds one pyramid level by accumulating raw RGBA rows pushed in via
/// [addRows], flushing a JPEG-encoded, file-written tile-row band as soon as
/// [PyramidLevelSpec.tileLength] rows have accumulated (or, in [finish], the
/// final shorter band once the source is exhausted). Each flushed band is
/// also box-filter-downsampled 2x and pushed into [next] — the next-coarser
/// level's own accumulator — cascading the whole pyramid from a single
/// stream of level-0 source bands, never holding more than a couple of
/// tile-row bands per level in memory at once.
class _LevelBuilder {
  final int levelIndex;
  final PyramidLevelSpec spec;
  final int quality;
  final _TileSink sink;
  _LevelBuilder? next;

  /// Set only on the coarsest level (the one with no [next] to cascade
  /// into) — that level's single [_emitBand] call covers its whole extent
  /// (already `<= tileSize` in both dimensions by construction), so this
  /// ends up being the complete coarsest-level image once [finish] returns.
  /// The exported file's thumbnail reuses it rather than decoding/
  /// downsampling the source a second time.
  img.Image? finalImage;

  final List<Uint8List> _pendingRows = [];

  _LevelBuilder({
    required this.levelIndex,
    required this.spec,
    required this.quality,
    required this.sink,
  });

  Future<void> addRows(List<Uint8List> rows) async {
    _pendingRows.addAll(rows);
    await _flushFullBands();
  }

  Future<void> finish() async {
    await _flushFullBands();
    if (_pendingRows.isNotEmpty) {
      final band = List<Uint8List>.of(_pendingRows);
      _pendingRows.clear();
      await _emitBand(band);
    }
    await next?.finish();
  }

  Future<void> _flushFullBands() async {
    while (_pendingRows.length >= spec.tileLength) {
      final band = _pendingRows.sublist(0, spec.tileLength);
      _pendingRows.removeRange(0, spec.tileLength);
      await _emitBand(band);
    }
  }

  Future<void> _emitBand(List<Uint8List> bandRows) async {
    final bandHeight = bandRows.length;
    final bandBytes = Uint8List(spec.width * bandHeight * 4);
    for (var r = 0; r < bandHeight; r++) {
      bandBytes.setRange(
        r * spec.width * 4,
        (r + 1) * spec.width * 4,
        bandRows[r],
      );
    }

    final bandImage = img.Image.fromBytes(
      width: spec.width,
      height: bandHeight,
      bytes: bandBytes.buffer,
      numChannels: 4,
      order: img.ChannelOrder.rgba,
    );
    if (next == null) finalImage = bandImage;
    for (var tx = 0; tx < spec.tilesAcrossX; tx++) {
      final tileLeft = tx * spec.tileWidth;
      final tileW = math.min(spec.tileWidth, spec.width - tileLeft);
      final tile = img.copyCrop(
        bandImage,
        x: tileLeft,
        y: 0,
        width: tileW,
        height: bandHeight,
      );
      await sink.writeTile(levelIndex, img.encodeJpg(tile, quality: quality));
    }

    if (next != null) {
      await next!.addRows(_boxDownsample2x(bandBytes, spec.width, bandHeight));
    }
  }
}

/// Box-filters [src] (tightly-packed RGBA, [width]x[height]) down by 2x in
/// both dimensions, returning the result as a list of rows (row-major, each
/// `ceil(width / 2) * 4` bytes) rather than a flat buffer — matches
/// [_LevelBuilder.addRows]'s input shape directly. A trailing odd row/column
/// is averaged from just its single remaining source pixel(s), the same
/// "round up" rule [computePyramidLevelDims] uses to size the next level.
List<Uint8List> _boxDownsample2x(Uint8List src, int width, int height) {
  final outWidth = (width / 2).ceil();
  final outHeight = (height / 2).ceil();
  final rows = <Uint8List>[];
  for (var oy = 0; oy < outHeight; oy++) {
    final y0 = oy * 2;
    final hasY1 = y0 + 1 < height;
    final row = Uint8List(outWidth * 4);
    for (var ox = 0; ox < outWidth; ox++) {
      final x0 = ox * 2;
      final hasX1 = x0 + 1 < width;
      var r = 0, g = 0, b = 0, a = 0, count = 0;
      void accum(int xx, int yy) {
        final idx = (yy * width + xx) * 4;
        r += src[idx];
        g += src[idx + 1];
        b += src[idx + 2];
        a += src[idx + 3];
        count++;
      }

      accum(x0, y0);
      if (hasX1) accum(x0 + 1, y0);
      if (hasY1) accum(x0, y0 + 1);
      if (hasX1 && hasY1) accum(x0 + 1, y0 + 1);

      row[ox * 4] = (r / count).round();
      row[ox * 4 + 1] = (g / count).round();
      row[ox * 4 + 2] = (b / count).round();
      row[ox * 4 + 3] = (a / count).round();
    }
    rows.add(row);
  }
  return rows;
}

/// An Aperio-style `ImageDescription` for the cropped file's level 0 —
/// enough for [SvsMetadata.parse] (via [SvsFile.open]) to recover [mpp] and
/// [appMag] when the exported file is reopened.
/// Fields from the source file's own `ImageDescription` that describe its
/// absolute position/size within the *original* slide — meaningless (and
/// actively misleading) once carried into a crop, so [_buildImageDescription]
/// drops them rather than copying them through with [sourceFields].
const _positionalMetadataFields = {
  'Left',
  'Top',
  'OriginalWidth',
  'OriginalHeight',
};

String _buildImageDescription({
  required int width,
  required int height,
  required int tileSize,
  required int quality,
  required double? mpp,
  required int? appMag,
  required Map<String, String> sourceFields,
}) {
  final header =
      'Aperio Image Library v1.0\r\n'
      '${width}x$height [0,0 ${width}x$height] ($tileSize x $tileSize) '
      'JPEG/RGB Q=$quality';
  final fields = <String>[
    if (appMag != null) 'AppMag = $appMag',
    if (mpp != null) 'MPP = ${mpp.toStringAsFixed(4)}',
    for (final entry in sourceFields.entries)
      // AppMag/MPP are recomputed above (MPP scales with the source level's
      // downsample, so the raw source value would be wrong here); every
      // other field the source file carried — Filename, Date, Time, User,
      // ScanScope ID, StripeWidth, DisplayColor, etc. — is preserved as-is.
      if (entry.key != 'AppMag' &&
          entry.key != 'MPP' &&
          !_positionalMetadataFields.contains(entry.key))
        '${entry.key} = ${entry.value}',
  ];
  return fields.isEmpty ? header : '$header|${fields.join('|')}';
}
